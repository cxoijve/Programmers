-- GRADE가 존재하는 개발자의 GRADE, ID, EMAIL을 조회
SELECT CASE
           WHEN (D.SKILL_CODE & F.CODE) > 0 AND (D.SKILL_CODE & P.CODE) > 0 THEN 'A'
           WHEN (D.SKILL_CODE & C.CODE) > 0 THEN 'B'
           WHEN (D.SKILL_CODE & F.CODE) > 0 THEN 'C'
       END AS GRADE,
       D.ID, D.EMAIL
FROM DEVELOPERS D 
JOIN (SELECT SUM(CODE) AS CODE FROM SKILLCODES WHERE CATEGORY = 'Front End') F
JOIN (SELECT CODE FROM SKILLCODES WHERE NAME = 'Python') P
JOIN (SELECT CODE FROM SKILLCODES WHERE NAME = 'C#') C

HAVING GRADE IS NOT NULL
ORDER BY GRADE ASC, ID ASC